/**
 * Regenerates the "AST node reference" section of README.md from the
 * authoritative visitor-key maps:
 *
 *   • `oxc-parser`                 → JS / TS / JSX nodes
 *   • `@glimmer/syntax` (prefixed) → Glimmer template nodes
 *
 * Classification rules (by node-type name prefix):
 *
 *   • `TS*`      → TypeScript-only, appears in `.gts`
 *   • `JSX*`     → JSX, not used by `.gjs` / `.gts`
 *   • `Glimmer*` → Glimmer template node, appears in both
 *   • anything else → core ESTree, appears in both
 *
 * Output is written between the `<!-- ast-nodes:start -->` and
 * `<!-- ast-nodes:end -->` markers in README.md, so hand-written prose around
 * the section is preserved.
 *
 * Usage:
 *   node scripts/generate-ast-node-reference.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { visitorKeys as oxcVisitorKeys } from "oxc-parser";

import { glimmerVisitorKeys } from "../src/transforms.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const README_PATH = join(HERE, "..", "README.md");
const START_MARKER = "<!-- ast-nodes:start -->";
const END_MARKER = "<!-- ast-nodes:end -->";

const groups = [
  {
    id: "core",
    title: "Core ESTree",
    scope: "in <code>.gjs</code> and <code>.gts</code>",
    match: (name) => !name.startsWith("TS") && !name.startsWith("JSX"),
    source: oxcVisitorKeys,
    blurb:
      "Standard JavaScript node types. Present in both `.gjs` and `.gts` — TypeScript is a superset of JavaScript, so `.gts` files may contain all of these too.",
  },
  {
    id: "ts",
    title: "TypeScript",
    scope: "<code>.gts</code> only",
    match: (name) => name.startsWith("TS"),
    source: oxcVisitorKeys,
    blurb: "TypeScript-specific nodes. Can only appear in `.gts` files.",
  },
  {
    id: "glimmer",
    title: "Glimmer template",
    scope: "in <code>.gjs</code> and <code>.gts</code>",
    match: () => true,
    source: glimmerVisitorKeys,
    blurb:
      "Nodes produced inside `<template>...</template>` regions by `@glimmer/syntax`, prefixed with `Glimmer` when spliced into the ESTree.",
  },
];

function formatKeys(keys) {
  if (!keys || keys.length === 0) return "_(leaf)_";
  return keys.map((k) => `\`${k}\``).join(", ");
}

function renderGroup(group) {
  const entries = Object.entries(group.source)
    .filter(([name]) => group.match(name))
    .sort(([a], [b]) => a.localeCompare(b));

  // Match oxfmt's table style: pad every cell so the column pipes line up.
  const NAME_HEADER = "Node";
  const KEYS_HEADER = "Child keys";
  const pairs = entries.map(([name, keys]) => [`\`${name}\``, formatKeys(keys)]);
  const nameW = Math.max(NAME_HEADER.length, ...pairs.map(([n]) => n.length));
  const keysW = Math.max(KEYS_HEADER.length, ...pairs.map(([, k]) => k.length));
  const pad = (s, w) => s + " ".repeat(w - s.length);
  const header = `| ${pad(NAME_HEADER, nameW)} | ${pad(KEYS_HEADER, keysW)} |`;
  const separator = `| ${"-".repeat(nameW)} | ${"-".repeat(keysW)} |`;
  const rows = pairs.map(([n, k]) => `| ${pad(n, nameW)} | ${pad(k, keysW)} |`).join("\n");

  return `<details>
<summary><strong>${group.title}</strong> — ${group.scope} (${entries.length} nodes)</summary>

${group.blurb}

${header}
${separator}
${rows}

</details>`;
}

function renderSection() {
  const inner = groups.map(renderGroup).join("\n\n");
  const total = groups.reduce(
    (sum, g) => sum + Object.keys(g.source).filter((k) => g.match(k)).length,
    0,
  );

  return `${START_MARKER}
<!-- Generated by scripts/generate-ast-node-reference.mjs — do not edit by hand. -->

## AST node reference

<details>
<summary><strong>Every AST node</strong> ember-estree may emit (${total} total) — grouped by which files they appear in</summary>

Generated from \`oxc-parser\`'s and \`@glimmer/syntax\`'s visitor-key maps. Re-run \`node scripts/generate-ast-node-reference.mjs\` after bumping either dependency to keep this in sync.

${inner}

</details>
${END_MARKER}`;
}

function logCounts() {
  const counts = groups.map((g) => ({
    title: g.title,
    count: Object.keys(g.source).filter((k) => g.match(k)).length,
  }));
  const total = counts.reduce((sum, c) => sum + c.count, 0);
  const width = Math.max(...counts.map((c) => c.title.length));

  for (const { title, count } of counts) {
    console.log(`  ${title.padEnd(width)}  ${count}`);
  }
  console.log(`  ${"total".padEnd(width)}  ${total}`);
}

function updateReadme() {
  const readme = readFileSync(README_PATH, "utf8");
  const section = renderSection();

  const startIdx = readme.indexOf(START_MARKER);
  const endIdx = readme.indexOf(END_MARKER);

  let next;
  if (startIdx === -1 || endIdx === -1) {
    // First run — inject before "## License" if present, otherwise append.
    const licenseIdx = readme.indexOf("\n## License");
    if (licenseIdx === -1) {
      next = `${readme.replace(/\s+$/, "")}\n\n${section}\n`;
    } else {
      const before = readme.slice(0, licenseIdx).replace(/\s+$/, "");
      next = `${before}\n\n${section}\n${readme.slice(licenseIdx)}`;
    }
  } else {
    const before = readme.slice(0, startIdx);
    const after = readme.slice(endIdx + END_MARKER.length);
    next = `${before}${section}${after}`;
  }

  logCounts();

  if (next === readme) {
    console.log("README already up to date.");
    return;
  }

  writeFileSync(README_PATH, next);
  console.log(`Updated ${README_PATH}`);
}

updateReadme();
